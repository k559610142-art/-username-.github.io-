// 龍騎士／幻術師／戰士 skills and skill books → data/extra-class-skills.js (merged into playerSkillData).
// Skills: DB `skills` rows, same field mapping as player-skill-data.js (checked: all 199 existing entries match).
// Books: DB etcitem rows with classname skill.Skill_DragonKnigh／Skill_Illusionist／Skill_WarriorSeal.
// Book → skill and level: Server_Game_2.jar item_etcitem/skill/Skill_DragonKnigh|Skill_Illusionist|Skill_WarriorSeal (skill, group)
// and data/cmd/Skill_Studying (group → minimum level): 龍騎士 51/52/53 = 15/30/45, 幻術師 61–64 = 10/20/30/40, 戰士 71–79 = 15/30/45/50/55/60/70/75/82.
// Usage: node tools/class-skills/build.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '../..');
function table(file) { const c = { GameDatabase: { register: (n, cols, rows) => { c.T = { cols, rows }; } } }; vm.createContext(c); vm.runInContext(fs.readFileSync(path.join(ROOT, 'data/database', file), 'utf8'), c); return c.T.rows.map(r => Object.fromEntries(c.T.cols.map((col, i) => [col.name, r[i]]))); }
const skillRows = new Map(table('table-138.js').map(r => [+r.skill_id, r]));
const etc = table('table-059.js');
const conv = r => ({ id: r.skill_id, name: r.name, circle: r.skill_level, mp: r.mpConsume, hp: r.hpConsume, material: r.itemConsumeId, materialCount: r.itemConsumeCount, reuse: r.reuseDelay, duration: r.buffDuration, target: r.target, damage: [r.damage_value, r.damage_dice, r.damage_dice_count], range: r.ranged, gfx: r.castgfx });
// [handler, role, skill → group] in the order the server handler lists them; group → level from Skill_Studying.
const LEVEL = { 51: 15, 52: 30, 53: 45, 61: 10, 62: 20, 63: 30, 64: 40, 71: 15, 72: 30, 73: 45, 74: 50, 75: 55, 76: 60, 77: 70, 78: 75, 79: 82 };
const CLASSES = [
  ['skill.Skill_DragonKnigh', '龍騎士', { 181: 51, 182: 51, 183: 51, 184: 51, 185: 52, 186: 52, 187: 52, 188: 52, 189: 52, 190: 52, 191: 52, 192: 52, 193: 53, 194: 53, 195: 53 }],
  ['skill.Skill_Illusionist', '幻術師', { 201: 61, 202: 61, 203: 61, 204: 61, 205: 61, 206: 61, 207: 61, 208: 61, 209: 62, 210: 62, 211: 62, 212: 62, 213: 63, 214: 63, 215: 63, 216: 63, 217: 64, 218: 64, 219: 64, 220: 64 }],
  ['skill.Skill_WarriorSeal', '戰士', { 225: 72, 226: 75, 228: 77, 229: 73, 230: 76, 233: 73, 234: 76, 235: 71, 236: 74, 237: 76, 238: 79, 239: 78 }],
];
const skills = {}, books = {};
for (const [handler, role, map] of CLASSES) {
  const ids = Object.keys(map).map(Number);
  for (const id of ids) skills[id] = conv(skillRows.get(id));
  // Books are matched by the skill name in the item name (戰士) or by order (龍騎士／幻術師: 15 and 20 consecutive items).
  const items = etc.filter(r => r.classname === handler).sort((a, b) => a.item_id - b.item_id);
  items.forEach((it, i) => {
    const inName = (it.name.match(/\((.*)\)/) || [])[1]?.replace(/[:：]\s*/, '：');
    const byName = ids.find(id => skills[id].name === inName), id = role === '戰士' ? byName : ids.slice().sort((a, b) => a - b)[i];
    if (!id) { console.log('找不到技能', it.item_id, it.name); return; }
    books[it.item_id] = { skill: id, min: { [role]: LEVEL[map[id]] }, element: '' };
  });
}
fs.writeFileSync(path.join(ROOT, 'data/extra-class-skills.js'),
  '// Generated by tools/class-skills/build.js: 龍騎士／幻術師／戰士 skills (DB skills) and skill books (DB etcitem + Skill_Studying levels).\n' +
  'Object.assign(playerSkillData.skills,' + JSON.stringify(skills) + ');\n' +
  'Object.assign(playerSkillData.books,' + JSON.stringify(books) + ');\n');
console.log('技能', Object.keys(skills).length, '技能書', Object.keys(books).length);
for (const [k, b] of Object.entries(books)) console.log(k, skills[b.skill].name, JSON.stringify(b.min));
