// 2026-11-20 玩家技能特效：原本 181 招技能只有 12 招有特效圖（NPC_EFFECT_DATA／potion-effect-data），其餘施法只有動作。
// 從原版客戶端 Sprite*.pak 依 list.spr 抽出技能 gfx 的特效圖格（原始位移、attr 混色、時間），寫 assets/skill-effects/ 與 data/skill-effect-data.js。
// 用法：node tools/build-skill-effects.cjs [客戶端資料夾]（預設 C:/Users/User/Desktop/天地劫天堂）
// 技能 gfx 清單在 tools/skill-effect-gfx.json（遊戲內 playerSkillData.skills 合併後、還沒有特效的 gfx）。
// 有方向的特效（dirs=1）抽 8 個方向 d0～d7，playEffect 依 heading 取；沒有方向的只有 d0。
const fs=require('node:fs'),path=require('node:path');
const {openPak}=require('./client-pak/l1pak.js'),{rgbaPng}=require('./client-pak/img2png.js'),{parseSpr,renderFrame}=require('./native-monsters/spr.js'),{parseList}=require('./native-monsters/listspr.js');
const root=path.resolve(__dirname,'..'),client=process.argv[2]||'C:/Users/User/Desktop/天地劫天堂',outDir=path.join(root,'assets/skill-effects');
fs.mkdirSync(outDir,{recursive:true});
const text=openPak(path.join(client,'Text.idx')),list=parseList(text.read(text.records.find(r=>r.name==='list.spr')).toString('latin1'));
const index=new Map();for(const f of ['Sprite.idx',...Array.from({length:16},(_,i)=>'Sprite'+String(i).padStart(2,'0')+'.idx')]){const p=path.join(client,f);if(!fs.existsSync(p))continue;const pak=openPak(p);for(const r of pak.records)if(/\.spr$/i.test(r.name))index.set(r.name.toLowerCase(),[pak,r]);}
const sprCache=new Map();function spr(name){if(!sprCache.has(name)){const rec=index.get(name);sprCache.set(name,rec?parseSpr(rec[0].read(rec[1])):null)}return sprCache.get(name)}
const roots=JSON.parse(fs.readFileSync(path.join(__dirname,'skill-effect-gfx.json'),'utf8'));
const out={},seen=new Set(),missing=[];
function build(id){
 if(seen.has(id))return;seen.add(id);
 const entry=list.get(id);if(!entry){missing.push(id+':no list.spr');return}
 const action=entry.actions[0]||entry.actions[3]||Object.values(entry.actions)[0];if(!action){missing.push(id+':no action');return}
 const src=entry.src||id,dirs=action.dirs===1?8:1,directions={};
 const parts=[...entry.raw.matchAll(/109\.effect\(\d+\s+(\d+)\)/g)].map(m=>+m[1]);
 for(let h=0;h<dirs;h++){
  const frames=[];
  for(let i=0;i<action.frames.length;i++){const f=action.frames[i],group=f.group+(dirs>1?h:0),sheet=spr(src+'-'+group+'.spr')||spr(id+'-'+group+'.spr');
   if(!sheet){frames.length=0;break}
   const r=renderFrame(sheet,f.frame);if(!r||!r.w||!r.h){frames.push(null);continue}
   const file='skill-'+id+'-'+h+'-'+i+'.png';fs.writeFileSync(path.join(outDir,file),rgbaPng(r.w,r.h,r.px));
   frames.push(['../skill-effects/'+file,r.x,r.y,r.w,r.h,f.dur*1000/(entry.frameRate||24)]);}
  const ok=frames.filter(Boolean);if(ok.length)directions['d'+h+'/idle']=ok;
 }
 if(!Object.keys(directions).length){missing.push(id+':no sprite');return}
 out[id]={attribute:entry.attr||+(entry.raw.match(/104\.attr\((\d+)\)/)||[])[1]||0,parts,directions};
 for(const child of parts)build(child);
}
for(const id of roots)build(id);
fs.writeFileSync(path.join(root,'data/skill-effect-data.js'),'// Generated by tools/build-skill-effects.cjs from original client sprites (player skill effects).\nfor(const [k,v] of Object.entries('+JSON.stringify(out)+'))if(!NPC_EFFECT_DATA[k])NPC_EFFECT_DATA[k]=v;\n');
console.log('built',Object.keys(out).length,'effects; missing',missing.length,missing.join(' '));
