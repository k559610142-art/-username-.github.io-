// 依 custom-actions.json 的人工動作表，把 list.spr 沒登錄的新外觀（目前是新遺忘之島 17 種）切成怪物圖。
// 輸出 assets/native-monsters/custom-mob-<gfx>-<n>.png 與 data/custom-monster-frames.js（載入時覆蓋 islandMonsterFrames[gfx]，
// 取代 dungeon-monster-data.js 退回的同名舊外觀）。不動 build.js 的產物。
// 用法：node tools/native-monsters/custom-looks.js [--client DIR]
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '../..');
const { openPak } = require('../client-pak/l1pak.js');
const { rgbaPng } = require('../client-pak/img2png.js');
const { parseSpr, renderFrame } = require('./spr.js');
const args = process.argv.slice(2), opt = { client: 'C:/Users/User/Desktop/天地劫天堂' };
for (let i = 0; i < args.length; i++) if (args[i] === '--client') opt.client = args[++i];
const cfg = JSON.parse(fs.readFileSync(path.join(__dirname, 'custom-actions.json'), 'utf8'));
const paks = ['Sprite.idx', ...Array.from({ length: 16 }, (_, i) => 'Sprite' + String(i).padStart(2, '0') + '.idx')].map(f => openPak(path.join(opt.client, f)));
const idx = new Map(); for (const p of paks) for (const r of p.records) if (/\.spr$/i.test(r.name)) idx.set(r.name.toLowerCase(), [p, r]);
const cache = new Map();
const spr = file => { if (!cache.has(file)) { const e = idx.get(file); cache.set(file, e ? parseSpr(e[0].read(e[1])) : null); } return cache.get(file); };
const KEYS = ['idle', 'walk', 'attack', 'cast', 'special', 'death'];

function clipsFor(gfx, look) {
  const out = {};
  for (let dir = 0; dir < 8; dir++) for (const key of KEYS) {
    if (look[key] === undefined) continue;
    const file = gfx + '-' + (look[key] * 8 + dir) + '.spr', s = spr(file); if (!s || !s.frames.length) continue;
    const total = look.ms?.[key] ?? cfg.default.ms[key], dur = Math.round(total / s.frames.length * 10) / 10;
    out['d' + dir + '/' + key] = s.frames.map((_, frame) => ({ file, frame, dur }));
  }
  return out['d0/idle'] && out['d0/walk'] ? out : null;
}
// 和 build.js 相同：用待機影格底端的中位數當腳底線
function yShift(clips) {
  const bottoms = []; for (const [key, list] of Object.entries(clips)) { if (!key.endsWith('/idle')) continue; for (const f of list) { const r = renderFrame(spr(f.file), f.frame); bottoms.push(r.y + r.h); } }
  bottoms.sort((a, b) => a - b); return -bottoms[Math.floor(bottoms.length / 2)];
}

const SHEET = 2048, frames = {}, files = [], outDir = path.join(ROOT, 'assets/native-monsters');
for (const f of fs.readdirSync(outDir)) if (/^custom-mob-/.test(f)) fs.unlinkSync(path.join(outDir, f));
for (const [gfx, look] of Object.entries(cfg.looks)) {
  const clips = clipsFor(gfx, look); if (!clips) { console.log(gfx, look.name, '切圖失敗（缺 idle／walk）'); continue; }
  const sheets = []; let sheet, cx = 0, cy = 0, rowH = 0;
  const newSheet = () => { sheet = { name: 'custom-mob-' + gfx + '-' + sheets.length + '.png', px: Buffer.alloc(SHEET * SHEET * 4), h: 0 }; sheets.push(sheet); cx = cy = rowH = 0; };
  newSheet(); const placed = new Map(), Y = yShift(clips); frames[gfx] = {};
  for (const [key, list] of Object.entries(clips)) frames[gfx][key] = list.map(f => {
    const id = f.file + '#' + f.frame; let p = placed.get(id);
    if (!p) {
      const r = renderFrame(spr(f.file), f.frame);
      if (cx + r.w > SHEET) { cx = 0; cy += rowH + 1; rowH = 0; }
      if (cy + r.h > SHEET) newSheet();
      for (let y = 0; y < r.h; y++) r.px.copy(sheet.px, ((cy + y) * SHEET + cx) * 4, y * r.w * 4, (y + 1) * r.w * 4);
      p = [sheet.name, r.x, r.y + Y, r.w, r.h, cx, cy]; placed.set(id, p);
      sheet.h = Math.max(sheet.h, cy + r.h); cx += r.w + 1; rowH = Math.max(rowH, r.h);
    }
    return [p[0], p[1], p[2], p[3], p[4], f.dur, p[5], p[6], SHEET];
  });
  for (const s of sheets) { const h = Math.max(1, s.h); fs.writeFileSync(path.join(outDir, s.name), rgbaPng(SHEET, h, s.px.subarray(0, SHEET * h * 4))); files.push(s.name); }
  console.log(gfx, look.name, Object.keys(clips).length + ' 段', sheets.length + ' 張圖');
}
fs.writeFileSync(path.join(ROOT, 'data/custom-monster-frames.js'),
  '// Generated by tools/native-monsters/custom-looks.js：list.spr 沒登錄的新外觀（新遺忘之島），動作表見 tools/native-monsters/custom-actions.json。\n' +
  '// 載在 dungeon-monster-data.js 之後，覆蓋原本退回的同名舊外觀。\n' +
  'for(const f of ' + JSON.stringify(files) + ')nativeMonsterFiles.add(f);\n' +
  'Object.assign(islandMonsterFrames,' + JSON.stringify(frames) + ');\n');
console.log('完成：', Object.keys(frames).length, '種，', files.length, '張圖');
