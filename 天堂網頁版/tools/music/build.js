// Background music from the 天地劫天堂 client: Text.pak music.def (map / area → track list, System Setting tracks)
// + Sound/music<N>.mp3. Copies only the tracks the game's maps (Map 0／4 + data/native-dungeon-maps.js) and system scenes use
// to assets/music/, and writes data/music-zones-data.js.
// Usage: node tools/music/build.js [--client DIR]
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.resolve(__dirname, '../..');
const { openPak } = require('../client-pak/l1pak.js');
const { parseMusicDef } = require('./parse-def.js');

const args = process.argv.slice(2); let client = 'C:/Users/User/Desktop/天地劫天堂';
for (let i = 0; i < args.length; i++) if (args[i] === '--client') client = args[++i];

const text = openPak(path.join(client, 'Text.idx'));
const def = parseMusicDef(text.read(text.records.find(r => /^music\.def$/i.test(r.name))).toString('latin1'));

const c = { window: {} }; vm.createContext(c);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'data/native-dungeon-maps.js'), 'utf8'), c);
const maps = new Set([0, 4, ...Object.keys(c.window.NATIVE_DUNGEON_MAPS).map(Number)]);

// Per map, in music.def order (the first matching area wins, a whole-map row is the fallback).
const zones = {};
for (const z of def.zones) if (maps.has(z.map)) (zones[z.map] ||= []).push(z.rect ? [...z.rect, z.tracks] : [z.tracks]);
const SYS = ['Login', 'Prince', 'Knight', 'Elf', 'Magician', 'Darkelf', 'DragonKnight', 'illusionist', 'Hunting', 'PledgeWar', 'Death', 'Fanfare'];
const sys = Object.fromEntries(SYS.filter(k => def.sys[k]).map(k => [k, def.sys[k]]));
sys.Title = 0; // music0.mp3: classic title theme (not listed in music.def), used on the login／character screens

const need = new Set([0, ...Object.values(sys)]); for (const list of Object.values(zones)) for (const z of list) for (const t of z[z.length - 1]) need.add(t);
const soundDir = path.join(client, 'Sound'), files = fs.readdirSync(soundDir), outDir = path.join(ROOT, 'assets/music');
fs.mkdirSync(outDir, { recursive: true });
const have = [], missing = []; let bytes = 0;
for (const n of [...need].sort((a, b) => a - b)) {
  const f = files.find(x => x.toLowerCase() === 'music' + n + '.mp3'); if (!f) { missing.push(n); continue; }
  const src = path.join(soundDir, f), dst = path.join(outDir, 'music' + n + '.mp3');
  if (!fs.existsSync(dst) || fs.statSync(dst).size !== fs.statSync(src).size) fs.copyFileSync(src, dst);
  have.push(n); bytes += fs.statSync(src).size;
}
// Drop tracks that no zone refers to any more.
for (const f of fs.readdirSync(outDir)) { const m = f.match(/^music(\d+)\.mp3$/); if (m && !need.has(+m[1])) fs.unlinkSync(path.join(outDir, f)); }
for (const list of Object.values(zones)) for (const z of list) { const t = z[z.length - 1].filter(n => have.includes(n)); z[z.length - 1] = t; }

fs.writeFileSync(path.join(ROOT, 'data/music-zones-data.js'),
  '// Generated by tools/music/build.js from the 天地劫天堂 client music.def: zones[map] = [[x1,y1,x2,y2,[tracks]] | [[tracks]], …] (first match wins); sys = System Setting tracks.\n' +
  'window.MUSIC_ZONES=' + JSON.stringify({ sys, tracks: have, zones }) + ';\n');
console.log('tracks', have.length, (bytes / 1e6).toFixed(1) + ' MB', 'missing', missing.join(' ') || '-', 'maps', Object.keys(zones).length + '/' + maps.size);
