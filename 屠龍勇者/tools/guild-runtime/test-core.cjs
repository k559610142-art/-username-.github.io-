assert.equal(G.resume(paused, { ticketId: t.ticketId }, NOW + 1).code, 'checkpoint_unverified');
assert(G.resume(paused, { ticketId: t.ticketId }, NOW + 1, trust).ok);
assert.equal(G.finish(state, 'success', { ...proof, simulationMs: 599999 }, [], NOW + 600000).code, 'proof_invalid');
assert.equal(G.finish(state, 'failed', null, ['sentinel'], NOW + 1).code, 'downed_invalid');
