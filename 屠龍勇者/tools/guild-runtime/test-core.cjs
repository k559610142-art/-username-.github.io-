assert.equal(G.normalize(state, { ...id, ownerId: 'account-B' }, NOW).code, 'identity_mismatch');
assert.equal(G.normalize(state, { ...id, created: id.created + 1 }, NOW).code, 'identity_mismatch');
assert.equal(G.normalize({ ...state, v: 99 }, id, NOW).code, 'unsupported_version');
assert.equal(G.normalize({ ...state, explored: { oversized: 'a'.repeat(140000) } }, id, NOW).code, 'state_too_large');
const offline = G.create({ ...id, ownerId: '' }, NOW);
assert(G.adoptOwner(offline, id, NOW).ok);
assert(!G.adoptOwner(state, { ...id, ownerId: 'account-B' }, NOW).ok);
assert.equal(G.begin(offline, ticket(offline), NOW, trust).code, 'ticket_identity');
let t = ticket(state);
assert.equal(G.begin(state, t, NOW).code, 'ticket_unverified');
assert.equal(G.begin(state, t, NOW, { verifyTicket: () => Promise.resolve(true) }).code, 'ticket_unverified');
assert.equal(G.begin(state, { ...t, ownerId: 'account-B' }, NOW, trust).code, 'ticket_identity');
assert.equal(G.begin(state, { ...t, expiresAt: NOW }, NOW, trust).code, 'ticket_invalid');
assert.equal(G.begin(state, { ...t, missionId: 'constructor' }, NOW, trust).code, 'ticket_invalid');
assert.equal(G.begin(state, { ...t, team: t.team.slice().reverse() }, NOW, trust).code, 'ticket_team');
const result = G.begin(state, t, NOW, { verifyTicket: payload => { payload.ownerId = 'modified'; return true; } });
assert(result.ok); assert.equal(t.ownerId, id.ownerId); assert.equal(result.state.activeTicket.ticket.ownerId, id.ownerId);
state = result.state;
assert.equal(JSON.stringify(G.create(id, NOW)), original, '呼叫不修改輸入');
