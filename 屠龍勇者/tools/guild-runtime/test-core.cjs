'use strict';
const assert = require('node:assert/strict');
const G = require('./core.cjs');
const NOW = 1793491200000;
const id = { ownerId: 'account-A', created: NOW - 86400000, cls: 'knight' };
const trust = { verifyTicket: () => true, verifyReceipt: () => true, verifyCheckpoint: () => true };
const proof = { logRef: 'guild/account-A/run-1', logHash: 'a'.repeat(64), simulationMs: 600000 };
function ticket(s, n = 1, missionId = 'lastCampfire') { return { ticketId: 'ticket-' + n, ownerId: s.ownerId, characterId: s.characterId,
    missionId, ruleVersion: G.RULE_VERSION, issuedAt: NOW, expiresAt: NOW + 7 * 86400000, seed: n, team: s.squad.slice() }; }
function accepted(s, t, seq = 1, recruits = []) { return { ownerId: s.ownerId, characterId: s.characterId, ticketId: t.ticketId,
    missionId: t.missionId, logHash: proof.logHash, ruleVersion: G.RULE_VERSION, seq, status: 'accepted', recruits }; }
for (const cls of Object.keys(G.INITIAL)) {
    const s = G.create({ ...id, cls }, NOW);
    assert.equal(s.members.length, 3); assert.equal(new Set(s.squad).size, 3);
    assert.deepEqual(s.squad, G.INITIAL[cls]);
    assert.equal(s.outbox.length, 0); assert.equal(s.activeTicket, null);
}
assert.equal(Object.keys(G.INITIAL).length, 12);
assert.equal(Object.keys(G.MISSIONS).length, 12);
assert.equal(G.ACTIVITIES.length, 7);
assert.throws(() => G.INITIAL.knight.push('sentinel'));
assert.throws(() => G.MEMBERS.sentinel.role = 'forged');
