import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c={Game:{},setTimeout,clearTimeout,performance};vm.createContext(c);
vm.runInContext(fs.readFileSync('data/interactions.js','utf8'),c);
const npc={x:5,y:6,name:'村民'},monster={x:10,y:10,attackable:true,hp:20,onAttack(){}};
const map={tileSize:32,npcs:[npc]};
assert.equal(c.Game.pickSceneTarget({x:176,y:180},map).kind,'talk','NPC name hit area');
assert.equal(c.Game.pickSceneTarget({x:176,y:208},map).entity,npc,'NPC body hit area');
assert.equal(c.Game.pickSceneTarget({x:336,y:336},map,[monster],()=>true).kind,'attack');
assert.equal(c.Game.pickSceneTarget({x:336,y:336},map,[monster],()=>false).kind,'move','No attack cursor without usable attack');
assert.equal(c.Game.pickSceneTarget({x:336,y:336},map,[{...monster,hp:0}],()=>true).kind,'move','Dead target');
assert.equal(c.Game.pickSceneTarget({x:16,y:16},map).kind,'move');
let time=0,seq=0;const timers=new Map(),listeners=new Map(),actions=[];
const canvas={addEventListener(n,fn){listeners.set(n,fn);},removeEventListener(n){listeners.delete(n);},setPointerCapture(){}};
const fire=(name,extra={})=>listeners.get(name)?.({pointerId:1,pointerType:'touch',button:0,clientX:100,clientY:100,detail:1,preventDefault(){},...extra});
const advance=ms=>{time+=ms;for(const [id,t]of [...timers])if(t.at<=time){timers.delete(id);t.fn();}};
const destroy=c.Game.bindScenePointer(canvas,{onActivate:(...a)=>actions.push(['activate',...a]),onMenu:(...a)=>actions.push(['menu',...a]),onHover:(...a)=>actions.push(['hover',...a])},{now:()=>time,schedule:(fn,delay)=>{timers.set(++seq,{fn,at:time+delay});return seq;},cancel:id=>timers.delete(id)});
fire('pointerdown');advance(80);fire('pointerup');fire('click');fire('click',{detail:0});
assert.equal(actions.filter(a=>a[0]==='activate').length,1,'Tap must not double-trigger compatibility click');
fire('pointerdown');fire('pointermove',{clientX:140});fire('pointerup',{clientX:140});
assert.equal(actions.filter(a=>a[0]==='activate').length,1,'Drag must not activate');
fire('pointerdown');advance(600);fire('contextmenu');fire('pointerup');
assert.equal(actions.filter(a=>a[0]==='menu').length,1,'Long press menu exactly once');
assert.equal(actions.filter(a=>a[0]==='activate').length,1,'Long press must not walk');
fire('pointerdown');fire('pointercancel');advance(600);
assert.equal(actions.filter(a=>a[0]==='menu').length,1,'Cancelled hold');
fire('pointerdown');fire('pointerdown',{pointerId:2});fire('pointerup');fire('pointerup',{pointerId:2});
assert.equal(actions.filter(a=>a[0]==='activate').length,1,'Multiple fingers must not activate');
advance(1600);fire('pointerdown',{pointerType:'mouse'});fire('pointerup',{pointerType:'mouse'});
assert.equal(actions.filter(a=>a[0]==='activate').length,2,'Mouse still works');
fire('contextmenu',{pointerType:'mouse'});assert.equal(actions.filter(a=>a[0]==='menu').length,2);
destroy();assert.equal(listeners.size,0);assert.equal(timers.size,0);
console.log('PASS cursor classification, NPC label/body hits, live/dead attack targets, touch tap, compatibility-click suppression, drag, long press, cancel, multi-touch, mouse and cleanup');
