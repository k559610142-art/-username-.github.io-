import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c={window:null};c.window=c;vm.createContext(c);
for(const name of ['config','world','village-map','adventure-map','characters','movement','camera'])vm.runInContext(fs.readFileSync(`data/${name}.js`,'utf8'),c);
const map=c.Game.adventureMap,m=c.Game.createMovement(map,map.spawn);
assert(m.go(20,40),'Village and plains must be connected');
for(let i=0;i<2000;i++)m.update(.01);
assert.equal(m.state.x,20);assert.equal(m.state.y,40);
assert.equal(map.sceneAt(m.state.y).id,'field-1-1');
assert(m.go(20,18),'Must be able to walk back to village');
for(let i=0;i<2000;i++)m.update(.01);
assert.equal(m.state.y,18);
assert(map.isBlocked(34,40),'River collision');
assert(map.isBlocked(9,34),'Ruin collision');
assert(map.isBlocked(25,46),'Camp collision');
const camera=c.Game.createCamera(1280,1792,960,600);
camera.follow(640,600);const initial=camera.y;
for(let i=0;i<100;i++)camera.follow(640,1300);
assert(camera.y>initial+500,'Camera must move with player');
const point=camera.screenToWorld(480,300);
assert(Math.abs(point.y-1300)<1);
camera.ready=false;camera.follow(0,0);assert.equal(camera.x,0);assert.equal(camera.y,0);
camera.ready=false;camera.follow(10000,10000);assert.equal(camera.x,320);assert.equal(camera.y,1192);
for(const f of fs.readdirSync('data').filter(f=>f.endsWith('.js')))new vm.Script(fs.readFileSync(`data/${f}`,'utf8'));
console.log('PASS village→plains→village walking, gate connection, water/ruin/camp collisions, follow camera, screen/world conversion, camera boundaries, syntax');
